def clean_num(v):
    if pd.isna(v):
        return None
    s = str(v).strip().replace(" ", "")
    if not s:
        return None
    if re.match(r"^\d{1,3}(,\d{3})+(\.\d+)?$", s):   # 1,234.56 / 1,234
        s = s.replace(",", "")
    elif "," in s and "." not in s:                 # 1234,56
        s = s.replace(",", ".")
    elif "," in s and "." in s and s.index(",") < s.index("."):
        s = s.replace(",", "")                      # 1,234.56
    m = re.match(r"^(-?\d+(?:\.\d+)?)(?:р\.?|руб\.?)?$", s, re.IGNORECASE)
    return float(m.group(1)) if m else None


